        // Process power throttling (Windows 10 1709+). With a control bit set and its state bit clear, Windows is told
        // never to apply that throttling to this process.
        private const int ProcessPowerThrottling = 4;
        private const uint PROCESS_POWER_THROTTLING_CURRENT_VERSION = 1;
        private const uint PROCESS_POWER_THROTTLING_EXECUTION_SPEED = 0x1;
        private const uint PROCESS_POWER_THROTTLING_IGNORE_TIMER_RESOLUTION = 0x4;

        [StructLayout(LayoutKind.Sequential)]
        private struct PROCESS_POWER_THROTTLING_STATE
        {
            public uint Version;
            public uint ControlMask;
            public uint StateMask;
        }

        [DllImport("kernel32.dll", SetLastError = true)]
        [return: MarshalAs(UnmanagedType.Bool)]
        private static extern bool SetProcessInformation(IntPtr hProcess, int processInformationClass, ref PROCESS_POWER_THROTTLING_STATE processInformation, uint processInformationSize);

        [DllImport("kernel32.dll")]
        private static extern IntPtr GetCurrentProcess();

        // Keep our 1 ms timer resolution and full CPU speed while minimized or hidden behind a game.
        // Best effort: older Windows rejects the timer-resolution flag, so fall back to execution speed alone.
        public static void OptOutOfPowerThrottling()
        {
            var state = new PROCESS_POWER_THROTTLING_STATE
            {
                Version = PROCESS_POWER_THROTTLING_CURRENT_VERSION,
                ControlMask = PROCESS_POWER_THROTTLING_EXECUTION_SPEED | PROCESS_POWER_THROTTLING_IGNORE_TIMER_RESOLUTION,
                StateMask = 0
            };
            uint size = (uint)Marshal.SizeOf<PROCESS_POWER_THROTTLING_STATE>();
            if (SetProcessInformation(GetCurrentProcess(), ProcessPowerThrottling, ref state, size)) return;

            state.ControlMask = PROCESS_POWER_THROTTLING_EXECUTION_SPEED;
            SetProcessInformation(GetCurrentProcess(), ProcessPowerThrottling, ref state, size);
        }

